CREATE TABLE KNOWLEDGE_CHUNK (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCE_NAME VARCHAR2(120 CHAR) NOT NULL,
    TITLE VARCHAR2(200 CHAR) NOT NULL,
    CHUNK_INDEX NUMBER(10) NOT NULL,
    CONTENT CLOB NOT NULL,
    NORMALIZED_CONTENT CLOB NOT NULL
);

CREATE INDEX IDX_KNOWLEDGE_CHUNK_SOURCE ON KNOWLEDGE_CHUNK (SOURCE_NAME);
CREATE INDEX IDX_KNOWLEDGE_CHUNK_SOURCE_CHUNK ON KNOWLEDGE_CHUNK (SOURCE_NAME, CHUNK_INDEX);
